public class datatypes {
        public static void main(String[] args){
        System.out.println("5 datatypes:");
        System.out.println("1. int");
        int integer = 10;
        System.out.println("Value of integer: " + integer);

        System.out.println("2. double");
        double decimal = 10.5;
        System.out.println("Value of decimal: " + decimal);

        System.out.println("3. char");
        char character = 'n';
        System.out.println("value of character: " + character);

        System.out.println("4. boolean");
        boolean bool = true;
        System.out.println("Value of boolean: " + bool);

        System.out.println("5. String");
        String text = "Hello, World!";
        System.out.println("Value of String: " + text);

    }
}

